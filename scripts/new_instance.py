"""Create a second cell that runs alongside the first. ``make new-instance``.

The point of the generator is what it does *not* do: it never touches code. A new area is
a new profile, a new ``.env`` and a Compose override with its own project name, ports and
volumes -- and that is the whole product claim. If adding an area required a code change,
this would be a framework, not a product.

Two isolation models, because both are legitimate and they answer different questions:

**Shared** (``--shared``) -- the instance brings only its own cell and joins the base
stack's networks. One Postgres, Redis, Qdrant and NATS for N cells; what keeps them apart
is the ``tenant_id`` + ``AGENT_FORGE_INSTANCE`` namespacing every key already carries,
which is precisely what that namespacing is for. Cheap: the tenth area costs one
container. Use it for several areas of one customer.

**Standalone** (the default) -- the instance clones the whole stack, its own stores
included. Harder blast radius: a corrupt Postgres cannot touch the neighbour. Use it for
tenants who require physical separation, or when one area's load should not be able to
starve another's.

The namespacing invariant holds either way. Under ``--shared`` it is the boundary; under
standalone it is defence in depth.

    uv run python scripts/new_instance.py --name ventas --tenant acme-mx --shared
    cd instances/acme-mx-ventas
    docker compose --env-file ../../.env --env-file .env --profile core up -d
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
INSTANCES = REPO_ROOT / "instances"
TEMPLATE_PROFILE = REPO_ROOT / "configs" / "agent.profile.example.yaml"

# Where the per-instance ports start. 8080 is the base cell, so the first generated
# instance takes 8180 and each one after it moves up by 100 -- enough room for the whole
# service block of an instance without overlapping the next.
PORT_BASE = 8080
PORT_STRIDE = 100
NAME_PATTERN = re.compile(r"^[a-z][a-z0-9-]{1,30}$")

ENV_TEMPLATE = """# Generated by `make new-instance NAME={name} TENANT={tenant}`.
#
# Only what differs from the base cell lives here. Everything else is inherited from the
# repository's `.env`, which is where shared infrastructure and secrets belong: two
# instances on one host share a Postgres, and duplicating its password into every
# instance directory is how one of the copies goes stale.

COMPOSE_PROJECT_NAME=agent-forge-{slug}

AGENT_FORGE_INSTANCE={name}
AGENT_FORGE_TENANT={tenant}
AGENT_FORGE_PROFILE=/app/configs/agent.profile.yaml

# Host ports. The container still listens on 8080; only the published side moves.
AGENT_API_PORT={api_port}
AGENT_PUBLIC_URL=http://127.0.0.1:{api_port}

# Evidence is per instance: one chain per tenant, and two instances writing the same
# chain would fork it, which fails verification in a way that looks like tampering.
LEDGER_PATH=/var/lib/agent-forge/ledger
{shared_env}"""

COMPOSE_TEMPLATE = """# Generated by `make new-instance NAME={name} TENANT={tenant}`.
#
# An override, not a copy. It includes the repository's compose file so a change there --
# a pinned image, a healthcheck, a resource limit -- reaches every instance. A generated
# full copy would drift from the original the first time anyone edited either.
#
#     cd instances/{slug}
#     docker compose --env-file ../../.env --env-file .env --profile core up -d
#
# Two env files, in that order: the repository's holds the shared infrastructure and its
# secrets, this one holds only what makes this instance different. Duplicating the
# secrets into every instance directory is how one of the copies goes stale.
#
# The published port comes from AGENT_API_PORT in this directory's `.env`; the base file
# already reads it, so there is nothing to override here.

include:
  - path: ../../deploy/compose/docker-compose.yml

services:
  agent-api:
    environment:
      AGENT_FORGE_INSTANCE: {name}
      AGENT_FORGE_PROFILE: /app/configs/agent.profile.yaml
    volumes:
      # This instance's profile shadows the image's default.
      - ./agent.profile.yaml:/app/configs/agent.profile.yaml:ro
      - {slug}-ledger:/var/lib/agent-forge/ledger

  ingestion-worker:
    environment:
      AGENT_FORGE_INSTANCE: {name}
      AGENT_FORGE_PROFILE: /app/configs/agent.profile.yaml
    volumes:
      - ./agent.profile.yaml:/app/configs/agent.profile.yaml:ro
      - {slug}-ledger:/var/lib/agent-forge/ledger

volumes:
  {slug}-ledger:
"""

SHARED_ENV = """
# Compose project of the BASE stack, whose networks this instance joins. Compose derives
# it from the directory the command runs in, so from the repository root it is the repo
# folder's name. Set it if you run the base stack under another project name.
BASE_COMPOSE_PROJECT=agentforge
"""

# `extends` and not `include`: include pulls in every service, so bringing the instance up
# under its own project name clones the entire stack -- the opposite of sharing. `extends`
# copies one service definition, healthcheck, cap_drop, limits and all, so this file still
# inherits changes to the base compose without inheriting its datastores.
SHARED_COMPOSE_TEMPLATE = """# Generated by `make new-instance NAME={name} TENANT={tenant}`
# with --shared.
#
# SHARED infrastructure. This file brings up only this cell; Postgres, Redis, Qdrant, NATS
# and LiteLLM belong to the base stack and are reached over its networks. What keeps two
# instances apart is the `tenant_id` + instance namespacing every key already carries --
# which is what that namespacing is for.
#
# The base stack has to be up first:
#
#     make up PROFILE=core
#     cd instances/{slug}
#     docker compose --env-file ../../.env --env-file .env --profile core up -d
#
# `extends`, not `include`: `include` would pull in every service and clone the whole
# stack under this project name. `extends` copies one service definition -- healthcheck,
# cap_drop, resource limits and all -- so this file still inherits changes to the base
# compose without inheriting its datastores.

services:
  agent-api:
    extends:
      file: ../../deploy/compose/docker-compose.yml
      service: agent-api
    # The base stack owns these. Waiting on services this project does not manage would
    # never resolve.
    depends_on: !reset []
    environment:
      AGENT_FORGE_INSTANCE: {name}
      AGENT_FORGE_PROFILE: /app/configs/agent.profile.yaml
    ports: !override
      - "127.0.0.1:{api_port}:8080"
    volumes: !override
      - ./agent.profile.yaml:/app/configs/agent.profile.yaml:ro
      - ledger-data:/var/lib/agent-forge/ledger

  ingestion-worker:
    extends:
      file: ../../deploy/compose/docker-compose.yml
      service: ingestion-worker
    depends_on: !reset []
    environment:
      AGENT_FORGE_INSTANCE: {name}
      AGENT_FORGE_PROFILE: /app/configs/agent.profile.yaml
    volumes: !override
      - ./agent.profile.yaml:/app/configs/agent.profile.yaml:ro
      - ledger-data:/var/lib/agent-forge/ledger

volumes:
  # Named explicitly so the chain is this instance's and survives the base stack being
  # recreated. Two instances writing one chain would fork it.
  ledger-data:
    name: {slug}-ledger

networks:
  frontend:
    external: true
    name: ${{BASE_COMPOSE_PROJECT:-agentforge}}_frontend
  backend:
    external: true
    name: ${{BASE_COMPOSE_PROJECT:-agentforge}}_backend
"""

