SHARED_NOTE = """
Esta instancia **comparte** la infraestructura del stack base: Postgres, Redis, Qdrant,
NATS, LiteLLM y el stack de observabilidad. Trae solo su propia celula y se une a las redes
del proyecto base (`BASE_COMPOSE_PROJECT` en el `.env` de este directorio).

Lo que las separa no es el contenedor: es que **cada clave lleva `tenant_id` + instancia**
en Redis, Postgres, Qdrant, Neo4j, NATS y el ledger. Para eso se construyo ese namespacing.

El stack base tiene que estar arriba antes:

```bash
make up PROFILE=core
```

Si un tenant exige separacion fisica de los almacenes, regenera la instancia **sin**
`--shared`: cada una traera los suyos."""

STANDALONE_NOTE = """
Esta instancia es un **stack completo**: trae sus propios Postgres, Redis, OPA y
LiteLLM.
Radio de impacto mas duro —una base corrupta no toca a la vecina— a cambio de N veces la
infraestructura en el mismo host.

Para varias areas de un mismo cliente suele sobrar: regenera con `--shared` y compartiran
los almacenes, con el aislamiento que ya da el namespacing por `tenant_id` + instancia."""


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--name", required=True, help="instance name, e.g. ventas")
    parser.add_argument("--tenant", required=True, help="tenant id, e.g. acme-mx")
    parser.add_argument("--area", default="", help="business area (defaults to --name)")
    parser.add_argument("--port", type=int, default=0, help="host port (default: next free)")
    parser.add_argument(
        "--shared",
        action="store_true",
        help=(
            "join the base stack's infrastructure instead of cloning it. Cheaper, and the "
            "isolation is the tenant_id + instance namespacing every key already carries"
        ),
    )
    parser.add_argument(
        "--force", action="store_true", help="overwrite an existing instance directory"
    )
    parser.add_argument("--root", type=Path, default=INSTANCES)
    return parser.parse_args(argv)


def next_port(root: Path) -> int:
    """The next port in the stride that no existing instance has taken."""
    used = set()
    for env in sorted(root.glob("*/.env")):
        for line in env.read_text(encoding="utf-8").splitlines():
            if line.startswith("AGENT_API_PORT="):
                with_value = line.split("=", 1)[1].strip()
                if with_value.isdigit():
                    used.add(int(with_value))
    port = PORT_BASE + PORT_STRIDE
    while port in used:
        port += PORT_STRIDE
    return port


def render_profile(template: str, *, name: str, tenant: str, area: str) -> str:
    """Point the example profile at this instance.

    A targeted rewrite of the identity block rather than a generated file: the example
    profile is the documented reference, comments included, and a generator that produced
    its own minimal version would quietly drop everything the reference explains.
    """
    template = _replace_persona(template, area)
    lines = template.splitlines()
    out: list[str] = []
    in_identity = False
    for line in lines:
        if line.startswith("identity:"):
            in_identity = True
            out.append(line)
            continue
        if in_identity and line and not line.startswith((" ", "#")):
            in_identity = False
        if in_identity:
            for key, value in (
                ("agent_name:", f'"asistente-{name}"'),
                ("area:", f'"{area}"'),
                ("tenant_id:", f'"{tenant}"'),
            ):
                stripped = line.strip()
                if stripped.startswith(key):
                    indent = line[: len(line) - len(line.lstrip())]
                    comment = line.split("#", 1)
                    trailing = f"  #{comment[1]}" if len(comment) > 1 else ""
                    line = f"{indent}{key} {value}{trailing}"
                    break
        out.append(line)
    header = (
        f"# Perfil de la instancia `{name}` (tenant `{tenant}`).\n"
        f"# Generado por `make new-instance`. Editable: es configuracion, no codigo.\n"
    )
    return header + "\n".join(out) + "\n"


def _replace_persona(template: str, area: str) -> str:
    """Swap the example persona for one that names this instance's area.

    Left alone, a generated `ventas` cell would introduce itself as the finance
    assistant -- a wrong default in the one field a user actually reads.
    """
    marker = "  persona: >"
    start = template.find(marker)
    if start < 0:
        return template
    end = template.find("\n\n", start)
    if end < 0:
        return template
    persona = (
        marker
        + "\n"
        + f"    Asistente experto del area de {area.capitalize()}. Formal, preciso, cita\n"
        + "    siempre sus fuentes. Si no encuentra respaldo documental, lo dice en lugar\n"
        + "    de suponer."
    )
    return template[:start] + persona + template[end:]


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    name = args.name.strip().lower()
    tenant = args.tenant.strip().lower()

    for label, value in (("--name", name), ("--tenant", tenant)):
        if not NAME_PATTERN.match(value):
            print(
                f"{label} must be lowercase letters, digits and hyphens, 2-31 chars: got {value!r}",
                file=sys.stderr,
            )
            return 2

    slug = f"{tenant}-{name}"
    target = args.root / slug
    if target.exists() and not args.force:
        print(f"{target} already exists; pass --force to overwrite", file=sys.stderr)
        return 2
    if target.exists():
        shutil.rmtree(target)

    port = args.port or next_port(args.root)
    area = args.area or name
    target.mkdir(parents=True)

    fields = {
        "name": name,
        "tenant": tenant,
        "slug": slug,
        "api_port": port,
        "area": area,
        "shared_env": SHARED_ENV if args.shared else "",
        "mode_label": "compartido" if args.shared else "independiente",
        "mode_note": SHARED_NOTE if args.shared else STANDALONE_NOTE,
    }
    compose = SHARED_COMPOSE_TEMPLATE if args.shared else COMPOSE_TEMPLATE
    (target / ".env").write_text(ENV_TEMPLATE.format(**fields), encoding="utf-8")
    (target / "docker-compose.yml").write_text(compose.format(**fields), encoding="utf-8")
    (target / "README.md").write_text(README_TEMPLATE.format(**fields), encoding="utf-8")
    (target / "agent.profile.yaml").write_text(
        render_profile(
            TEMPLATE_PROFILE.read_text(encoding="utf-8"), name=name, tenant=tenant, area=area
        ),
        encoding="utf-8",
    )

    print(f"instance {slug} created at {target}")
    mode = "shared infrastructure" if args.shared else "standalone stack"
    print(f"  isolation : {mode}")
    print(f"  port      : 127.0.0.1:{port}")
    print(f"  profile   : {target / 'agent.profile.yaml'}")
    print("\nnext:")
    if args.shared:
        print("  make up PROFILE=core          # the base stack has to be up first")
    print(f"  cd instances/{slug}")
    print("  docker compose --env-file ../../.env --env-file .env --profile core up -d")
    print(f"  curl -s http://127.0.0.1:{port}/health/ready")
    print("\nno source file was modified.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
