"""Generate eval cases from a tenant's own ingested corpus.

The seed datasets in ``evals/datasets/`` are synthetic and small, which is right for a
committed fixture and wrong for measuring a real deployment: they say nothing about the
documents a particular tenant actually has. This turns an ingested corpus into cases, so a
new area has a dataset the same day it has a corpus.

Every question is generated by the **local** model and every case keeps the chunk id it
came from, which is what makes the generated answer checkable rather than merely
plausible.

The output is **not** committed. A generated dataset carries the tenant's content by
construction; it belongs next to the corpus it came from, under the same access control.

    uv run python evals/synthetic/generate.py --area finanzas --limit 50 \\
        --out /secure/evals/finanzas.jsonl
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
from contextlib import AsyncExitStack
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from agent_forge.core.classification import Classification  # noqa: E402
from agent_forge.observability.logging import configure_logging, get_logger  # noqa: E402

log = get_logger(__name__)

PROMPT = (
    "Lee el fragmento y escribe UNA pregunta que se responda unicamente con el. "
    "La pregunta debe ser natural, en espanol, y no debe mencionar que existe un "
    "fragmento. Responde solo con la pregunta."
)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--area", default="", help="restrict to one area (default: all)")
    parser.add_argument("--limit", type=int, default=50, help="how many cases to generate")
    parser.add_argument("--out", type=Path, required=True, help="destination JSONL")
    parser.add_argument(
        "--max-classification",
        default="C2",
        help="skip chunks above this level (default C2: keep C3/C4 out of a dataset file)",
    )
    parser.add_argument("--groups", default="", help="comma-separated groups for the requester")
    return parser.parse_args(argv)


async def generate(args: argparse.Namespace) -> int:
    from agent_forge.runtime import Settings, build_runtime

    ceiling = Classification.parse(args.max_classification)
    env = dict(os.environ)
    env.setdefault("AGENT_FORGE_INSTANCE", "synthetic")

    async with AsyncExitStack() as stack:
        runtime = await build_runtime(Settings.from_env(env), stack, env=env)
        chunks = await _sample_chunks(runtime, args.area, args.limit, ceiling)
        if not chunks:
            print("no chunks matched; is the corpus ingested?", file=sys.stderr)
            return 1

        cases: list[dict[str, Any]] = []
        for index, chunk in enumerate(chunks):
            question = await _ask_for_a_question(runtime, chunk)
            if not question:
                continue
            cases.append(
                {
                    "id": f"syn-{index:03d}",
                    "question": question,
                    # No `expects`: a generated gold answer would only be as good as the
                    # model that wrote it. The chunk id is the checkable part.
                    "expects": [],
                    "sources": [chunk.chunk_id],
                    "requester": {
                        "user_id": "u-synthetic",
                        "groups": [g for g in args.groups.split(",") if g],
                        "ceiling": str(ceiling),
                    },
                }
            )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8") as handle:
        for case in cases:
            handle.write(json.dumps(case, ensure_ascii=False) + "\n")
    print(f"wrote {len(cases)} cases -> {args.out}")
    print(
        "reminder: this file contains tenant content. Do not commit it; store it under the "
        "same access control as the corpus it came from."
    )
    return 0


async def _sample_chunks(runtime: Any, area: str, limit: int, ceiling: Classification) -> list[Any]:
    """Chunks worth generating from: long enough to hold a fact, and within the ceiling.

    Read through the store's own access filter rather than around it. A generator that
    scrolled the raw collection would happily produce questions about material nobody is
    entitled to, and the resulting dataset would then be impossible to share.
    """
    from agent_forge.knowledge.access_control import AccessFilter

    store = runtime.knowledge.vector_store
    found = await store.scroll(
        AccessFilter(tenant_id=runtime.tenant_id, ceiling=ceiling), limit=limit * 4
    )
    picked = [
        chunk
        for chunk in found
        if len(chunk.text) > 120
        and Classification.parse(chunk.classification) <= ceiling
        and (not area or area in str(chunk.metadata.get("area", area)))
    ]
    return picked[:limit]


async def _ask_for_a_question(runtime: Any, chunk: Any) -> str:
    try:
        reply = await runtime.gateway.complete(
            [
                {"role": "system", "content": PROMPT},
                {"role": "user", "content": chunk.text},
            ],
            classification=Classification.parse(chunk.classification),
            preferred=[runtime.profile.models.fast],
            tenant_id=runtime.tenant_id,
            temperature=0.4,
            max_tokens=80,
        )
    except Exception as exc:  # one bad chunk must not end the run
        log.warning("synthetic.generation_failed", detail=f"{type(exc).__name__}: {exc}"[:200])
        return ""
    return reply.content.strip().splitlines()[0].strip() if reply.content.strip() else ""


def main(argv: list[str] | None = None) -> int:
    configure_logging(level=os.environ.get("LOG_LEVEL", "WARNING"), fmt="console")
    return asyncio.run(generate(parse_args(argv)))


if __name__ == "__main__":
    raise SystemExit(main())
